// ── 20/21. WIRE: api-remotes tsconfig.{host,client}.json ────────────────────
// Robust approach: insert a new reference as the LAST entry of the references
// array via regex, so comma placement is always correct regardless of whether
// pve-host is currently last. Skips if already wired.
for (const rel of ['packages/api/remotes/tsconfig.host.json', 'packages/api/remotes/tsconfig.client.json']) {
  const abs = join(ROOT, rel)
  let t = readFileSync(abs, 'utf8')
  const check = `"../../${slug}/${slug}-host"`
  if (t.includes(check)) { console.log(`  = ${rel} (already wired)`); continue }
  const refBlock = new RegExp(`("references"\\s*:\\s*\\[)([\\s\\S]*?)(\\n\\s*\\])`)
  if (!refBlock.test(t)) { console.error(`  ! references array not found in ${rel}`); process.exit(1) }
  t = t.replace(refBlock, (m, open, body, close) => {
    // if body has a trailing `},` without a following entry, trim the comma
    const cleaned = body.replace(/},\s*$/, '}')
    return `${open}${cleaned},\n    {\n      "path": "../../${slug}/${slug}-host"\n    }${close}`
  })
  writeFileSync(abs, t); console.log(`  ~ ${rel}`)
}

// ── 22. WIRE: api-remotes src/client/index.ts ───────────────────────────────
{
  const rel = 'packages/api/remotes/src/client/index.ts'
  const abs = join(ROOT, rel)
  let rt = readFileSync(abs, 'utf8')
  const importLine = `import ${camel}Remote from '${hostPkg}/remote'`
  const typeLine = `export type {} from '${hostPkg}/remote'`
  const contribLine = `      commandsRemote, goalsRemote, dynamicRemote, pluginInventoryRemote, messageFeedbackRemote, dingtalkRemote, pveRemote, ${camel}Remote,`
  const check = `${hostPkg}/remote`
  if (rt.includes(check)) {
    console.log(`  = ${rel} (already wired)`)
  } else {
    // 1) insert side-effect import right after the pveRemote import line
    rt = rt.replace(/import pveRemote from '@deepseek-ai\/dsh-pve-host\/remote'\n/, (m) => `${m}${importLine}\n`)
    // 2) insert type-only re-export right after the pve type-line
    rt = rt.replace(/export type \{\} from '@deepseek-ai\/dsh-pve-host\/remote'\n/, (m) => `${m}${typeLine}\n`)
    // 3) append the mount contribution to the apply() array
    rt = rt.replace(/commandsRemote, goalsRemote, dynamicRemote, pluginInventoryRemote, messageFeedbackRemote, dingtalkRemote, pveRemote,/, (m) => `${m} ${camel}Remote,`)
    writeFileSync(abs, rt)
    console.log(`  ~ ${rel}`)
  }
}

