// ── helpers ──────────────────────────────────────────────────────────────────
function w(rel, content) {
  const abs = join(ROOT, rel); mkdirSync(dirname(abs), { recursive: true })
  writeFileSync(abs, content); console.log(`  + ${rel}`)
}
function patchJson(rel, fn) {
  const abs = join(ROOT, rel); const d = JSON.parse(readFileSync(abs, 'utf8'))
  fn(d); writeFileSync(abs, JSON.stringify(d, null, 2) + '\n'); console.log(`  ~ ${rel}`)
}
function patchText(rel, anchor, add, check) {
  const abs = join(ROOT, rel); let t = readFileSync(abs, 'utf8')
  if (check && t.includes(check)) { console.log(`  = ${rel} (already wired)`); return }
  if (!t.includes(anchor)) { console.error(`  ! anchor not found in ${rel}`); process.exit(1) }
  t = t.replace(anchor, anchor + '\n' + add)
  writeFileSync(abs, t); console.log(`  ~ ${rel}`)
}

