w(`packages/client/ui-wh-${slug}/src/client/${Pascal}.tsx`,
`import { useEffect, useState } from 'react'
import { Button, Input, Modal } from '@deepseek-ai/dsh-client-ui-primitives'
import type {
  ${Pascal}DeleteRequest, ${Pascal}DeleteResult,
  ${Pascal}Item, ${Pascal}ItemInput,
  ${Pascal}ListRequest, ${Pascal}ListResult,
  ${Pascal}SaveRequest, ${Pascal}SaveResult,
} from '${hostPkg}/types'
import type { RemoteResult } from '@deepseek-ai/dsh-typert-protocol'
import css from './${Pascal}.module.css'
import type { ${Pascal}Key } from './locales.ts'

export interface ${Pascal}ConfigProps {
  t: (key: ${Pascal}Key) => string
  listItems: (_request: ${Pascal}ListRequest) => Promise<RemoteResult<${Pascal}ListResult>>
  saveItem: (request: ${Pascal}SaveRequest) => Promise<RemoteResult<${Pascal}SaveResult>>
  deleteItem: (request: ${Pascal}DeleteRequest) => Promise<RemoteResult<${Pascal}DeleteResult>>
}

export type ${Pascal}Injected = Omit<${Pascal}ConfigProps, 't'>

export function ${Pascal}Config({ t, listItems, saveItem, deleteItem }: ${Pascal}ConfigProps) {
  const [items, setItems] = useState<${Pascal}Item[]>([])
  const [modalOpen, setModalOpen] = useState(false)
  const [editing, setEditing] = useState<${Pascal}Item | null>(null)
  const [name, setName] = useState('')
  const [enabled, setEnabled] = useState(true)
  const [deleteTarget, setDeleteTarget] = useState<${Pascal}Item | null>(null)

  const refresh = async () => {
    const r = await listItems({})
    if (r.ok && r.value.ok) setItems([...r.value.value.items])
  }
  useEffect(() => { void refresh() }, [])

  const openAdd = () => { setEditing(null); setName(''); setEnabled(true); setModalOpen(true) }
  const openEdit = (item: ${Pascal}Item) => { setEditing(item); setName(item.name); setEnabled(item.enabled); setModalOpen(true) }
  const closeModal = () => { setModalOpen(false); setEditing(null) }

  const handleSave = async () => {
    if (name.trim().length === 0) return
    const input: ${Pascal}ItemInput = {
      id: editing?.id ?? crypto.randomUUID(),
      name: name.trim(),
      enabled,
    }
    const r = await saveItem({ input })
    if (r.ok && r.value.ok) { closeModal(); await refresh() }
  }

  const confirmDelete = async () => {
    if (deleteTarget === null) return
    await deleteItem({ id: deleteTarget.id })
    setDeleteTarget(null)
    await refresh()
  }

  return (
    <div className={css.panel}>
      <div className={css.panelHeader}>
        <h3>{t('title')}</h3>
        <Button variant="outline" size="sm" onClick={openAdd}>{t('action.add')}</Button>
      </div>
      <ul className={css.list}>
        {items.map(item => (
          <li key={item.id} className={css.item}>
            <span>{item.name}</span>
            <span className={item.enabled ? css.on : css.off}>{item.enabled ? '●' : '○'}</span>
            <Button variant="ghost" size="sm" onClick={() => openEdit(item)}>{t('action.edit')}</Button>
            <Button variant="ghost" size="sm" onClick={() => setDeleteTarget(item)}>{t('action.delete')}</Button>
          </li>
        ))}
        {items.length === 0 && <li className={css.empty}>{t('list.empty')}</li>}
      </ul>

      <Modal open={modalOpen} onClose={closeModal} title={editing ? t('action.edit') : t('action.add')}
        closeLabel={t('action.close')}
        footer={(<><Button variant="ghost" onClick={closeModal}>{t('action.cancel')}</Button>
          <Button variant="primary" onClick={handleSave}>{t('action.save')}</Button></>)}>
        <label className={css.field}>
          <span>{t('field.name')}</span>
          <Input value={name} onChange={e => setName(e.target.value)} />
        </label>
      </Modal>

      <Modal open={deleteTarget !== null} onClose={() => setDeleteTarget(null)} title={t('delete.title')}
        closeLabel={t('action.close')}
        footer={(<><Button variant="ghost" onClick={() => setDeleteTarget(null)}>{t('action.cancel')}</Button>
          <Button variant="primary" onClick={confirmDelete}>{t('action.delete')}</Button></>)}>
        <p>{t('delete.confirm')}</p>
      </Modal>
    </div>
  )
}
`)

